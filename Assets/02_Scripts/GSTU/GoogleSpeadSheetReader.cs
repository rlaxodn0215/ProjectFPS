            catalogs.Clear();
            foreach (var import in reader.Imports)
            {
                var field = new ObjectField(import.catalogPath) { objectType = typeof(ScriptableObject), value = import.catalog, allowSceneObjects = false };
                field.SetEnabled(false);
                catalogs.Add(field);
            }
        }).Every(200);
        return root;
    }
