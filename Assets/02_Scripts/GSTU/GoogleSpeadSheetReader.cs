        root.Add(status); root.Add(error); root.Add(sheetList); root.Add(catalogs);
        string snapshot = null;
        root.schedule.Execute(() =>
        {
            if (reader == null) return;
            settings.SetEnabled(!reader.IsBusy);
            actions.SetEnabled(!reader.IsBusy && !EditorApplication.isCompiling && !EditorApplication.isPlayingOrWillChangePlaymode && !EditorUtility.scriptCompilationFailed);
